func TestFixExpr(t *testing.T) {
	cases := []struct{ in, want string }{
		{`DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now'))`, `DEFAULT (` + NowExpr + `)`},
		{`month GLOB '[0-9][0-9][0-9][0-9]-[0-1][0-9]'`, `month ~ '^[0-9][0-9][0-9][0-9]-[0-1][0-9]$'`},
		{`code GLOB '[A-Z0-9]*'`, `code ~ '^[A-Z0-9].*$'`},
		{`x GLOB '1*'`, `x ~ '^1.*$'`},
		{`NEW.a IS NOT OLD.a`, `NEW.a IS DISTINCT FROM OLD.a`},
		{`NEW.a IS OLD.a`, `NEW.a IS NOT DISTINCT FROM OLD.a`},
		{`a IS NULL AND b IS NOT NULL`, `a IS NULL AND b IS NOT NULL`},
		{`WHERE d.date <= date('now', '+9 hours')`, `WHERE d.date <= to_char(now() AT TIME ZONE 'Asia/Seoul', 'YYYY-MM-DD')`},
		{`substr(date(NEW.created_at, '+9 hours'), 1, 7)`, `substr(to_char((NEW.created_at)::timestamp AT TIME ZONE 'UTC' AT TIME ZONE 'Asia/Seoul', 'YYYY-MM-DD'), 1, 7)`},
		{`'이것은 IS NOT x 문자열'`, `'이것은 IS NOT x 문자열'`}, // 문자열 안은 그대로
	}
	for _, c := range cases {
		if got := fixExpr(c.in); got != c.want {
			t.Errorf("fixExpr(%q)\n got  %q\n want %q", c.in, got, c.want)
		}
	}
}

func TestCreateTable(t *testing.T) {
	got, err := translateCreateTable(`CREATE TABLE "x" (
		id INTEGER PRIMARY KEY AUTOINCREMENT, -- 주석 INTEGER
		name TEXT NOT NULL UNIQUE,
		n INTEGER NOT NULL DEFAULT 0 CHECK (n IN (0,1)),
		img BLOB,
		ratio REAL,
		at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now')),
		PRIMARY KEY (id)
	)`)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"CREATE TABLE x (", "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "n BIGINT NOT NULL DEFAULT 0", "img BYTEA", "ratio DOUBLE PRECISION", "to_char(now()"} {
		if !strings.Contains(got, want) {
			t.Errorf("%q 가 없음:\n%s", want, got)
		}
	}
	if strings.Contains(got, "주석") || strings.Contains(strings.ToUpper(got), "INTEGER") {
		t.Errorf("주석·INTEGER 가 남음:\n%s", got)
	}
	// 단일 행 표(CHECK (id = 1))와 audit_logs.seq 는 식별자가 아니다.
	one, err := translateCreateTable(`CREATE TABLE app_one (id INTEGER PRIMARY KEY CHECK (id = 1), v TEXT)`)
	if err != nil || strings.Contains(one, "IDENTITY") || !strings.Contains(one, "id BIGINT PRIMARY KEY") {
		t.Errorf("단일 행 표: %v\n%s", err, one)
	}
	// 다른 표를 가리키는 1:1 키(user_id)와 id 가 아닌 키는 식별자가 아니다.
	ref, err := translateCreateTable(`CREATE TABLE u_opts (user_id INTEGER PRIMARY KEY REFERENCES users(id), v TEXT)`)
	if err != nil || strings.Contains(ref, "IDENTITY") || !strings.Contains(ref, "user_id BIGINT PRIMARY KEY REFERENCES users(id)") {
		t.Errorf("1:1 키: %v\n%s", err, ref)
	}
	aud, err := TranslateStatement(`CREATE TABLE audit_logs (seq INTEGER PRIMARY KEY AUTOINCREMENT, at TEXT NOT NULL)`)
	if err != nil || strings.Contains(aud, "IDENTITY") || !strings.Contains(aud, "seq BIGINT PRIMARY KEY") {
		t.Errorf("audit_logs.seq: %v\n%s", err, aud)
	}
	if got := IdentityColumn("t", `CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, a TEXT)`); got != "id" {
		t.Errorf("IdentityColumn = %q", got)
	}
	if got := IdentityColumn("audit_logs", `CREATE TABLE audit_logs (seq INTEGER PRIMARY KEY AUTOINCREMENT)`); got != "" {
		t.Errorf("audit_logs 는 식별자 없음: %q", got)
	}
}

func TestTriggerTranslation(t *testing.T) {
	simple, err := TranslateStatement(`CREATE TRIGGER trg_a_no_update BEFORE UPDATE ON audit_logs
		BEGIN SELECT RAISE(ABORT, 'audit_logs 는 추가 전용입니다'); END`)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"CREATE FUNCTION trg_a_no_update_fn() RETURNS trigger LANGUAGE plpgsql",
		"RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'audit_logs 는 추가 전용입니다';",
		"RETURN NEW;",
		"CREATE TRIGGER trg_a_no_update BEFORE UPDATE ON audit_logs FOR EACH ROW EXECUTE FUNCTION trg_a_no_update_fn()",
	} {
		if !strings.Contains(simple, want) {
			t.Errorf("%q 가 없음:\n%s", want, simple)
		}
	}
	del, _ := TranslateStatement(`CREATE TRIGGER t_d BEFORE DELETE ON x BEGIN SELECT RAISE(ABORT, 'm'); END`)
	if !strings.Contains(del, "RETURN OLD;") {
		t.Errorf("BEFORE DELETE 는 OLD 를 돌려준다:\n%s", del)
	}
	cond, err := TranslateStatement(`CREATE TRIGGER t_c BEFORE UPDATE OF status, x ON j WHEN NEW.status <> OLD.status AND NEW.a IS NOT OLD.a
		BEGIN SELECT RAISE(ABORT, 'a') WHERE (SELECT COUNT(*) FROM k WHERE k.id = NEW.id) < 2; SELECT RAISE(ABORT, '두 번째 ''따옴표'''); END`)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"BEFORE UPDATE OF status, x ON j", "IF NEW.status <> OLD.status AND NEW.a IS DISTINCT FROM OLD.a THEN", "IF (SELECT COUNT(*) FROM k WHERE k.id = NEW.id) < 2 THEN", "MESSAGE = '두 번째 ''따옴표'''"} {
		if !strings.Contains(cond, want) {
			t.Errorf("%q 가 없음:\n%s", want, cond)
		}
	}
	after, err := TranslateStatement(`CREATE TRIGGER t_a AFTER INSERT ON r WHEN NEW.id > 0 BEGIN INSERT OR IGNORE INTO u (a) SELECT NEW.id; DELETE FROM v WHERE g = NEW.id; END`)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"INSERT INTO u (a) SELECT NEW.id ON CONFLICT DO NOTHING;", "DELETE FROM v WHERE g = NEW.id;", "RETURN NULL;"} {
		if !strings.Contains(after, want) {
			t.Errorf("%q 가 없음:\n%s", want, after)
		}
	}
}

func TestSplitStatements(t *testing.T) {
	src := `-- 주석; 세미콜론
CREATE TABLE a (x INTEGER); /* 블록; 주석 */
INSERT INTO a VALUES (1); INSERT INTO a VALUES ('a;b');
CREATE TRIGGER t BEFORE UPDATE ON a BEGIN SELECT RAISE(ABORT, 'x;y') WHERE 1; SELECT CASE WHEN 1 THEN 2 END; END;
CREATE INDEX i ON a(x);`
	got := SplitStatements(src)
	if len(got) != 5 {
		t.Fatalf("문장 5개여야 한다: %d\n%q", len(got), got)
	}
	if !strings.HasPrefix(got[3], "CREATE TRIGGER") || !strings.HasSuffix(got[3], "END") {
		t.Errorf("트리거 본문의 ; 로 나뉘면 안 된다: %q", got[3])
	}
}

func TestSortTablesCycle(t *testing.T) {
	ts := []Table{
		{Name: "a", SQL: `CREATE TABLE a (id INTEGER PRIMARY KEY, b_id INTEGER REFERENCES b(id))`},
		{Name: "b", SQL: `CREATE TABLE b (id INTEGER PRIMARY KEY, a_id INTEGER REFERENCES a(id) ON DELETE CASCADE)`},
		{Name: "c", SQL: `CREATE TABLE c (id INTEGER PRIMARY KEY, a_id INTEGER REFERENCES a(id), self INTEGER REFERENCES c(id))`},
	}
	s, err := SortTables(ts)
	if err != nil {
		t.Fatal(err)
	}
	if len(s.Tables) != 3 {
		t.Fatalf("%v", s.Tables)
	}
	// 순환을 닫는 참조는 미뤄진다(어느 쪽이든 하나).
	deferred := 0
	for _, m := range s.Deferred {
		deferred += len(m)
	}
	if deferred != 1 {
		t.Fatalf("순환 간선 하나가 미뤄져야 한다: %v", s.Deferred)
	}
	var alters []string
	for _, tb := range s.Tables {
		_, al, err := TranslateCreateTable(tb.SQL, s.Deferred[tb.Name])
		if err != nil {
			t.Fatal(err)
		}
		alters = append(alters, al...)
	}
	if len(alters) != 1 || !strings.Contains(alters[0], "ADD FOREIGN KEY") {
		t.Fatalf("ALTER 한 문장: %v", alters)
	}
}

func TestCastSumsAndLiteral(t *testing.T) {
	if got := castSums(`SELECT COALESCE(SUM(l.qty_delta), 0) AS x, SUM(CASE WHEN a THEN b END) FROM t`); !strings.Contains(got, "SUM(l.qty_delta)::BIGINT") || !strings.Contains(got, "SUM(CASE WHEN a THEN b END)::BIGINT") {
		t.Errorf("castSums: %s", got)
	}
	if Literal(nil, "TEXT") != "NULL" || Literal(int64(7), "INTEGER") != "7" || Literal("it's", "TEXT") != "'it''s'" {
		t.Error("Literal 기본")
	}
	if Literal("2026-11-12T11:28:49Z", "TEXT") != NowExpr {
		t.Error("시각 문자열은 적용 시각 식으로 바뀐다")
	}
	if Literal([]byte{0xde, 0xad}, "BLOB") != `'\xdead'::bytea` {
		t.Error("BLOB")
	}
}
