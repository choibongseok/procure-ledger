func TestPGRebindAndDialectFragments(t *testing.T) {
	db := pgtest.Open(t, 5)
	ctx := context.Background()
	d := dbutil.Postgres

	if _, err := db.ExecContext(ctx, `CREATE TABLE t (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT UNIQUE NOT NULL, n BIGINT)`); err != nil {
		t.Fatal(err)
	}
	// `?` 자리표시자는 연결 계층이 $n 으로 바꾼다.
	var id int64
	if err := db.QueryRowContext(ctx, `INSERT INTO t (name, n) VALUES (?, ?) RETURNING id`, "a", 1).Scan(&id); err != nil || id != 1 {
		t.Fatalf("INSERT RETURNING: %d, %v", id, err)
	}
	// 문자열 안의 ? 는 그대로 둔다.
	var q string
	if err := db.QueryRowContext(ctx, `SELECT '뭐?' || ?::text`, "!").Scan(&q); err != nil || q != "뭐?!" {
		t.Fatalf("문자열 안의 ?: %q, %v", q, err)
	}

	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		t.Fatal(err)
	}
	defer tx.Rollback()
	nid, err := dbutil.InsertID(ctx, tx, `INSERT INTO t (name, n) VALUES (?, ?)`, "b", nil)
	if err != nil || nid != 2 {
		t.Fatalf("InsertID: %d, %v", nid, err)
	}
	res, err := tx.ExecContext(ctx, `INSERT INTO t (name, n) VALUES (?, ?)`+dbutil.OnConflictDoNothing, "a", 9)
	if err != nil {
		t.Fatal(err)
	}
	if n, _ := res.RowsAffected(); n != 0 {
		t.Fatalf("충돌은 무시되어야 한다: %d", n)
	}
	var cnt int
	if err := tx.QueryRowContext(ctx, `SELECT COUNT(*) FROM t WHERE n IS DISTINCT FROM 1`).Scan(&cnt); err != nil || cnt != 1 {
		t.Fatalf("IS DISTINCT FROM: %d, %v", cnt, err)
	}
	var agg string
	if err := tx.QueryRowContext(ctx, `SELECT string_agg(name, ',' ORDER BY id) FROM t`).Scan(&agg); err != nil || agg != "a,b" {
		t.Fatalf("string_agg: %q, %v", agg, err)
	}

	// 방언 조각이 PG 에서 SQLite 와 같은 값을 낸다.
	var now string
	if err := tx.QueryRowContext(ctx, `SELECT `+d.NowUTC()).Scan(&now); err != nil || len(now) != 20 || now[10] != 'T' || !strings.HasSuffix(now, "Z") {
		t.Fatalf("NowUTC: %q, %v", now, err)
	}
	var kst string
	if err := tx.QueryRowContext(ctx, `SELECT `+d.KSTDate("'2026-01-01T16:00:00Z'")).Scan(&kst); err != nil || kst != "2026-01-02" {
		t.Fatalf("KSTDate: %q, %v", kst, err)
	}
	var diff int
	if err := tx.QueryRowContext(ctx, `SELECT `+d.DayDiff("'2026-03-10'", "'2026-03-01'")).Scan(&diff); err != nil || diff != 9 {
		t.Fatalf("DayDiff: %d, %v", diff, err)
	}
	var g int
	if err := tx.QueryRowContext(ctx, `SELECT `+d.Greatest("3", "7")).Scan(&g); err != nil || g != 7 {
		t.Fatalf("Greatest: %d, %v", g, err)
	}
	// 세션 설정(UTC)
	var tz string
	if err := tx.QueryRowContext(ctx, `SHOW TIME ZONE`).Scan(&tz); err != nil || tz != "UTC" {
		t.Fatalf("시간대: %q, %v", tz, err)
	}
}

func TestPGErrorHelpersAgainstServer(t *testing.T) {
	db := pgtest.Open(t, 3)
	ctx := context.Background()
	for _, s := range []string{
		`CREATE TABLE p (id BIGINT PRIMARY KEY)`,
		`CREATE TABLE c (id BIGINT PRIMARY KEY, p_id BIGINT NOT NULL REFERENCES p(id), n BIGINT CHECK (n >= 0), name TEXT UNIQUE)`,
		`CREATE FUNCTION c_guard() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'c 는 수정할 수 없습니다' USING ERRCODE = 'P0001'; END $$`,
		`CREATE TRIGGER trg_c_no_update BEFORE UPDATE ON c FOR EACH ROW EXECUTE FUNCTION c_guard()`,
		`INSERT INTO p VALUES (1)`,
		`INSERT INTO c VALUES (1, 1, 1, 'x')`,
	} {
		if _, err := db.ExecContext(ctx, s); err != nil {
			t.Fatalf("%s: %v", s, err)
		}
	}
	_, err := db.ExecContext(ctx, `INSERT INTO c VALUES (2, 1, 1, 'x')`)
	if !dbutil.IsUnique(err) {
		t.Errorf("유일 위반: %v", err)
	}
	_, err = db.ExecContext(ctx, `INSERT INTO c VALUES (3, 99, 1, 'y')`)
	if !dbutil.IsForeignKey(err) {
		t.Errorf("외래 키 위반: %v", err)
	}
	_, err = db.ExecContext(ctx, `INSERT INTO c VALUES (4, 1, -1, 'z')`)
	if !dbutil.IsCheck(err) {
		t.Errorf("CHECK 위반: %v", err)
	}
	_, err = db.ExecContext(ctx, `INSERT INTO c VALUES (5, 1, 1, NULL), (5, 1, 1, NULL)`)
	if !dbutil.IsUnique(err) {
		t.Errorf("기본 키 중복: %v", err)
	}
	_, err = db.ExecContext(ctx, `UPDATE c SET n = 2 WHERE id = 1`)
	if !dbutil.IsGuard(err, "수정할 수 없습니다") || dbutil.IsGuard(err, "다른 메시지") {
		t.Errorf("트리거 보호 장치: %v", err)
	}
}

func TestPGTxManagerRetriesDeadlock(t *testing.T) {
	db := pgtest.Open(t, 6)
	ctx := context.Background()
	if _, err := db.ExecContext(ctx, `CREATE TABLE r (id BIGINT PRIMARY KEY, v BIGINT NOT NULL)`); err != nil {
		t.Fatal(err)
	}
	if _, err := db.ExecContext(ctx, `INSERT INTO r VALUES (1, 0), (2, 0)`); err != nil {
		t.Fatal(err)
	}
	m := dbutil.PGTxManager{DB: db, Sleep: func(d time.Duration) {}}
	// 두 트랜잭션이 서로 반대 순서로 같은 두 행을 잠근다 → 하나는 교착(40P01)으로 중단되고 재시도로 성공해야 한다.
	var attempts atomic.Int32
	var ready sync.WaitGroup
	ready.Add(2)
	run := func(first, second int64) error {
		firstTry := true
		return m.WithTx(ctx, func(tx contract.Tx) error {
			attempts.Add(1)
			if _, err := tx.ExecContext(ctx, `UPDATE r SET v = v + 1 WHERE id = ?`, first); err != nil {
				return err
			}
			if firstTry { // 첫 시도에서만 두 쪽이 각자 첫 행을 잠근 뒤 교차한다
				firstTry = false
				ready.Done()
				ready.Wait()
			}
			_, err := tx.ExecContext(ctx, `UPDATE r SET v = v + 1 WHERE id = ?`, second)
			return err
		})
	}
	var wg sync.WaitGroup
	errs := make([]error, 2)
	wg.Add(2)
	go func() { defer wg.Done(); errs[0] = run(1, 2) }()
	go func() { defer wg.Done(); errs[1] = run(2, 1) }()
	wg.Wait()
	for i, e := range errs {
		if e != nil {
			t.Fatalf("트랜잭션 %d: %v", i, e)
		}
	}
	var v1, v2 int
	if err := db.QueryRowContext(ctx, `SELECT (SELECT v FROM r WHERE id=1), (SELECT v FROM r WHERE id=2)`).Scan(&v1, &v2); err != nil {
		t.Fatal(err)
	}
	if v1 != 2 || v2 != 2 {
		t.Fatalf("두 트랜잭션이 각각 한 번씩만 반영되어야 한다: %d, %d", v1, v2)
	}
	if attempts.Load() < 3 {
		t.Fatalf("교착으로 한 번은 다시 시도해야 한다(시도 %d회)", attempts.Load())
	}
}

func TestPGTxManagerBusyOnLockTimeout(t *testing.T) {
	db, dbURL := pgtest.OpenURL(t, 4)
	ctx := context.Background()
	if _, err := db.ExecContext(ctx, `CREATE TABLE l (id BIGINT PRIMARY KEY)`); err != nil {
		t.Fatal(err)
	}
	holder, err := db.BeginTx(ctx, nil)
	if err != nil {
		t.Fatal(err)
	}
	defer holder.Rollback()
	if _, err := holder.ExecContext(ctx, `LOCK TABLE l IN ACCESS EXCLUSIVE MODE`); err != nil {
		t.Fatal(err)
	}
	// 연결마다 lock_timeout 이 걸려 있으므로 짧게 줄여 기다림 초과를 확인한다.
	short, err := dbutil.OpenPG(ctx, dbURL, dbutil.PGOptions{MaxConns: 2, AllowInsecure: true, LockTimeout: 300 * time.Millisecond})
	if err != nil {
		t.Fatal(err)
	}
	defer short.Close()
	m := dbutil.PGTxManager{DB: short}
	err = m.WithTx(ctx, func(tx contract.Tx) error {
		_, e := tx.ExecContext(ctx, `INSERT INTO l VALUES (1)`)
		return e
	})
	if !errors.Is(err, dbutil.ErrBusy) {
		t.Fatalf("잠금 대기 초과는 ErrBusy 여야 한다: %v", err)
	}
}

func TestPGAdvisoryLockSerializes(t *testing.T) {
	db := pgtest.Open(t, 6)
	ctx := context.Background()
	if _, err := db.ExecContext(ctx, `CREATE TABLE a (n BIGINT NOT NULL)`); err != nil {
		t.Fatal(err)
	}
	m := dbutil.PGTxManager{DB: db}
	var wg sync.WaitGroup
	var inside atomic.Int32
	var maxInside atomic.Int32
	for i := 0; i < 8; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			err := m.WithTx(ctx, func(tx contract.Tx) error {
				if err := dbutil.AcquireTxLock(ctx, tx, dbutil.Postgres, dbutil.LockAuditChain); err != nil {
					return err
				}
				cur := inside.Add(1)
				for {
					m := maxInside.Load()
					if cur <= m || maxInside.CompareAndSwap(m, cur) {
						break
					}
				}
				var n sql.NullInt64
				if err := tx.QueryRowContext(ctx, `SELECT MAX(n) FROM a`).Scan(&n); err != nil {
					return err
				}
				time.Sleep(5 * time.Millisecond)
				_, err := tx.ExecContext(ctx, `INSERT INTO a VALUES (?)`, n.Int64+1)
				inside.Add(-1)
				return err
			})
			if err != nil {
				t.Errorf("tx: %v", err)
			}
		}()
	}
	wg.Wait()
	if maxInside.Load() != 1 {
		t.Fatalf("advisory lock 안에는 한 번에 하나만 있어야 한다: %d", maxInside.Load())
	}
	var cnt, mx int
	if err := db.QueryRowContext(ctx, `SELECT COUNT(*), MAX(n) FROM a`).Scan(&cnt, &mx); err != nil || cnt != 8 || mx != 8 {
		t.Fatalf("빈틈없이 1..8: count=%d max=%d err=%v", cnt, mx, err)
	}
}

func TestPGInstanceLockSingle(t *testing.T) {
	db := pgtest.Open(t, 6)
	ctx := context.Background()
	key := dbutil.LockKey(dbutil.LockServerInstance)
	held := func() int {
		var n int
		q := `SELECT COUNT(*) FROM pg_locks WHERE locktype='advisory' AND granted AND classid = ((?::bigint >> 32) & 4294967295)::oid AND objid = (?::bigint & 4294967295)::oid`
		if err := db.QueryRowContext(ctx, q, key, key).Scan(&n); err != nil {
			t.Fatal(err)
		}
		return n
	}
	rel1, err := dbutil.AcquireInstanceLock(ctx, db, dbutil.Postgres)
	if err != nil {
		t.Fatal(err)
	}
	// 같은 데이터베이스에 두 번째 서버: 풀의 다른 연결이라도 잡지 못한다.
	if _, err := dbutil.AcquireInstanceLock(ctx, db, dbutil.Postgres); !errors.Is(err, dbutil.ErrInstanceBusy) {
		t.Fatalf("두 번째 잡기는 ErrInstanceBusy 여야 한다: %v", err)
	}
	if n := held(); n != 1 {
		t.Fatalf("세션 advisory 잠금이 pg_locks 에 1개 있어야 한다: %d", n)
	}
	rel1() // 첫 연결을 닫으면 다시 잡힌다.
	rel2, err := dbutil.AcquireInstanceLock(ctx, db, dbutil.Postgres)
	if err != nil {
		t.Fatalf("해제 뒤에는 다시 잡혀야 한다: %v", err)
	}
	rel2()
	if n := held(); n != 0 {
		t.Fatalf("해제 뒤 잠금이 남음: %d", n)
	}
}

