export function actionLabel(action: string): string {
  if (ACTION_LABELS[action]) return ACTION_LABELS[action];
  if (action.startsWith("mcp.")) {
    // 쓰기 도구는 실행 전 "mcp.<도구>" 와 실행 후 "mcp.<도구>.result" 두 건을 남긴다.
    const isResult = action.endsWith(".result");
    const tool = TOOL_LABELS[action.slice(4, isResult ? -".result".length : undefined)];
    if (!tool) return "AI 도구 호출";
    return isResult ? `AI 도구 결과: ${tool}` : `AI 도구: ${tool}`;
  }
  return FALLBACK_ACTION;
}

