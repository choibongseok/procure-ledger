const READABLE = /^[가-힣0-9\s.,()·\-]+$/;

/**
 * 비고(detail). 서버가 남긴 원문(`tool=… required=approval:decide`, `status=ok provider=…`)은 그대로 내지 않는다.
 * 필요 권한은 한국어 권한 이름으로 바꾸고, 한글 문장만 그대로 보이며, 나머지는 보이지 않는다.
 */
export function detailText(detail: string): string {
  if (!detail) return "";
  if (detail === "requested") return "실행 요청";
  const perm = /(?:required=|필요 권한 )([a-z_]+:[a-z_]+)/.exec(detail);
  if (perm) return `필요 권한: ${PERMISSION_LABELS[perm[1]] ?? "해당 권한"}`;
  return READABLE.test(detail) ? detail : "";
}

/** 대상 번호. 세션 해시·접근 경로 같은 내부 식별자는 숨기고, `pr:12` 형태는 번호만 보인다. */
export function targetIdText(targetType: string, targetId: string): string {
  if (targetType === "session" || targetType === "route" || targetId === "-") return "";
  const m = /^(?:pr|po|doc):(\d+)$/.exec(targetId);
  if (m) return `#${m[1]}`;
  const scope = /^(role|department|user):(.+)$/.exec(targetId);
  if (scope) {
    const kind: Record<string, string> = { role: "역할", department: "부서", user: "사용자" };
    return `${kind[scope[1]]} ${VALUE_LABELS[scope[2]] ?? scope[2]}`;
  }
  if (targetType === "policy") {
    const policy: Record<string, string> = { "0": "대상 없음", search: "질의 검색", related: "작성 화면 관련 조항" };
    if (policy[targetId]) return policy[targetId];
  }
  const words: Record<string, string> = { chain: "전체", search: "검색", pending: "대기 목록", new: "신규", related: "관련 조항", alerts: "재고 경보" };
  if (words[targetId]) return words[targetId];
  return /^\d+$/.test(targetId) ? `#${targetId}` : targetId;
}
