/** 역할이 권한을 가졌는지 본다. 알 수 없는 역할·권한은 false. */
export function roleHas(role: string | undefined, perm: PermissionOrOpen): boolean {
  if (perm === "public") return true;
  if (!role) return false;
  if (perm === "authenticated") return true;
  const list = (ROLE_PERMISSIONS as Record<string, readonly Permission[]>)[role];
  return !!list && list.includes(perm);
}
