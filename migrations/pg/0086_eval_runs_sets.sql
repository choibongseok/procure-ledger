-- 추가 전용(0050)은 끝난 행에 그대로 적용한다. 진행 중(running) 행만 마감 때 한 번 고칠 수 있다.
CREATE OR REPLACE FUNCTION trg_eval_runs_no_update_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF OLD.status <> 'running' THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'eval_runs 는 추가 전용입니다';
  END IF;
  RETURN NEW;
END
$fn$;

CREATE TABLE eval_run_items (
    run_id        BIGINT NOT NULL REFERENCES eval_runs(id),
    item_seq      BIGINT NOT NULL,
    pass          BIGINT NOT NULL CHECK (pass IN (0,1)),
    score         BIGINT NOT NULL DEFAULT 0 CHECK (score BETWEEN 0 AND 100),
    latency_ms    BIGINT NOT NULL DEFAULT 0,
    input_tokens  BIGINT NOT NULL DEFAULT 0,
    output_tokens BIGINT NOT NULL DEFAULT 0,
    detail        TEXT NOT NULL DEFAULT '' CHECK (length(detail) <= 300),
    PRIMARY KEY (run_id, item_seq)
);

CREATE TABLE eval_gates (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purpose_label TEXT NOT NULL UNIQUE CHECK (length(purpose_label) BETWEEN 1 AND 80),
    set_id        BIGINT NOT NULL REFERENCES eval_sets(id),
    enabled       BIGINT NOT NULL DEFAULT 1 CHECK (enabled IN (0,1)),
    updated_by    BIGINT REFERENCES users(id),
    updated_at    TEXT NOT NULL
);
