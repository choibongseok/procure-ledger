CREATE TABLE webhook_subscriptions (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 TEXT NOT NULL UNIQUE CHECK (length(name) BETWEEN 1 AND 40),
    secret_sealed        TEXT NOT NULL,
    hint                 TEXT NOT NULL DEFAULT '',
    events_json          TEXT NOT NULL DEFAULT '[]',
    include_api          BIGINT NOT NULL DEFAULT 0 CHECK (include_api IN (0,1)),
    active               BIGINT NOT NULL DEFAULT 1 CHECK (active IN (0,1)),
    paused_reason        TEXT NOT NULL DEFAULT '' CHECK (paused_reason IN ('','auto','manual')),
    consecutive_failures BIGINT NOT NULL DEFAULT 0 CHECK (consecutive_failures >= 0),
    cursor_seq           BIGINT NOT NULL DEFAULT 0 CHECK (cursor_seq >= 0),
    last_ok_at           TEXT NOT NULL DEFAULT '',
    last_error_code      TEXT NOT NULL DEFAULT '',
    last_error_at        TEXT NOT NULL DEFAULT '',
    created_by           BIGINT REFERENCES users(id),
    created_at           TEXT NOT NULL,
    updated_at           TEXT NOT NULL
);
CREATE FUNCTION trg_webhook_subscriptions_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '웹훅 구독은 지울 수 없습니다(사용 중지만 됩니다)';
  RETURN OLD;
END
$fn$;
CREATE TRIGGER trg_webhook_subscriptions_no_delete BEFORE DELETE ON webhook_subscriptions FOR EACH ROW EXECUTE FUNCTION trg_webhook_subscriptions_no_delete_fn();

CREATE TABLE webhook_deliveries (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT NOT NULL REFERENCES webhook_subscriptions(id),
    event_seq       BIGINT NOT NULL,
    resource        TEXT NOT NULL,
    object_id       BIGINT NOT NULL,
    event_type      TEXT NOT NULL,
    event_status    TEXT NOT NULL DEFAULT '',
    event_at        TEXT NOT NULL,
    status          TEXT NOT NULL DEFAULT 'queued' CHECK (status IN ('queued','sending','sent','failed','skipped')),
    attempts        BIGINT NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    resends         BIGINT NOT NULL DEFAULT 0 CHECK (resends >= 0),
    next_try_at     TEXT NOT NULL,
    claimed_at      TEXT NOT NULL DEFAULT '',
    last_try_at     TEXT NOT NULL DEFAULT '',
    last_code       TEXT NOT NULL DEFAULT '',
    created_at      TEXT NOT NULL,
    sent_at         TEXT NOT NULL DEFAULT '',
    UNIQUE (subscription_id, event_seq)
);
CREATE INDEX idx_webhook_deliveries_due ON webhook_deliveries(status, next_try_at);
CREATE INDEX idx_webhook_deliveries_object ON webhook_deliveries(subscription_id, resource, object_id, event_seq);
CREATE INDEX idx_webhook_deliveries_sub ON webhook_deliveries(subscription_id, status);

CREATE FUNCTION trg_webhook_deliveries_status_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF NEW.status <> OLD.status AND NOT (
    (OLD.status = 'queued'  AND NEW.status IN ('sending','skipped')) OR
    (OLD.status = 'sending' AND NEW.status IN ('sent','queued','failed')) OR
    (OLD.status = 'failed'  AND NEW.status = 'queued')) THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '웹훅 발송 건의 상태 전이가 올바르지 않습니다';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER trg_webhook_deliveries_status BEFORE UPDATE OF status ON webhook_deliveries FOR EACH ROW EXECUTE FUNCTION trg_webhook_deliveries_status_fn();

CREATE FUNCTION trg_webhook_deliveries_fixed_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF NEW.subscription_id <> OLD.subscription_id OR NEW.event_seq <> OLD.event_seq OR NEW.resource <> OLD.resource OR NEW.object_id <> OLD.object_id
  OR NEW.event_type <> OLD.event_type OR NEW.event_status <> OLD.event_status OR NEW.event_at <> OLD.event_at OR NEW.created_at <> OLD.created_at THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '웹훅 발송 건의 구독·이벤트는 바꿀 수 없습니다';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER trg_webhook_deliveries_fixed BEFORE UPDATE ON webhook_deliveries FOR EACH ROW EXECUTE FUNCTION trg_webhook_deliveries_fixed_fn();

CREATE FUNCTION trg_webhook_deliveries_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF OLD.status IN ('queued','sending') THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '처리 중인 웹훅 발송 건은 지울 수 없습니다';
  END IF;
  RETURN OLD;
END
$fn$;
CREATE TRIGGER trg_webhook_deliveries_no_delete BEFORE DELETE ON webhook_deliveries FOR EACH ROW EXECUTE FUNCTION trg_webhook_deliveries_no_delete_fn();

