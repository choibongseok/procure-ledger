CREATE TABLE tax_invoice_matches (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id  BIGINT NOT NULL REFERENCES tax_invoices(id),
    status      TEXT NOT NULL CHECK (status IN ('proposed','confirmed','dismissed','unlinked')),
    result      TEXT NOT NULL CHECK (result IN ('match','ambiguous','amount_diff','vendor_unknown','no_receipt')),
    receipt_key TEXT NOT NULL DEFAULT '',
    diff_json   TEXT NOT NULL DEFAULT '{}',
    warn_json   TEXT NOT NULL DEFAULT '[]',
    proposed_at TEXT NOT NULL,
    decided_by  BIGINT REFERENCES users(id),
    decided_at  TEXT NOT NULL DEFAULT '',
    comment     TEXT NOT NULL DEFAULT '' CHECK (length(comment) <= 200)
);
CREATE UNIQUE INDEX idx_tax_matches_one_proposed ON tax_invoice_matches(invoice_id) WHERE status = 'proposed';
CREATE UNIQUE INDEX idx_tax_matches_one_confirmed ON tax_invoice_matches(invoice_id) WHERE status = 'confirmed';
CREATE INDEX idx_tax_matches_status ON tax_invoice_matches(status, proposed_at);

CREATE FUNCTION trg_tax_matches_status_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF NEW.status <> OLD.status AND NOT (
    (OLD.status = 'proposed'  AND NEW.status IN ('confirmed','dismissed')) OR
    (OLD.status = 'confirmed' AND NEW.status = 'unlinked')) THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '세금계산서 대조의 상태 전이가 올바르지 않습니다';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER trg_tax_matches_status BEFORE UPDATE OF status ON tax_invoice_matches FOR EACH ROW EXECUTE FUNCTION trg_tax_matches_status_fn();

CREATE FUNCTION trg_tax_matches_fixed_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF NEW.id <> OLD.id OR NEW.invoice_id <> OLD.invoice_id OR NEW.proposed_at <> OLD.proposed_at
  OR (OLD.status <> 'proposed' AND (NEW.result <> OLD.result OR NEW.receipt_key <> OLD.receipt_key OR NEW.diff_json <> OLD.diff_json OR NEW.warn_json <> OLD.warn_json)) THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '확정·기각된 대조 결과는 고칠 수 없습니다';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER trg_tax_matches_fixed BEFORE UPDATE ON tax_invoice_matches FOR EACH ROW EXECUTE FUNCTION trg_tax_matches_fixed_fn();

CREATE FUNCTION trg_tax_matches_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '세금계산서 대조 기록은 지울 수 없습니다';
  RETURN OLD;
END
$fn$;
CREATE TRIGGER trg_tax_matches_no_delete BEFORE DELETE ON tax_invoice_matches FOR EACH ROW EXECUTE FUNCTION trg_tax_matches_no_delete_fn();

CREATE TABLE tax_invoice_match_receipts (
    match_id   BIGINT NOT NULL REFERENCES tax_invoice_matches(id),
    po_id      BIGINT NOT NULL REFERENCES purchase_orders(id),
    receipt_id BIGINT NOT NULL REFERENCES receipts(id),
    journal_id BIGINT REFERENCES journals(id),
    confirmed  BIGINT NOT NULL DEFAULT 0 CHECK (confirmed IN (0,1)),
    PRIMARY KEY (match_id, receipt_id)
);
CREATE UNIQUE INDEX idx_tax_match_receipts_confirmed ON tax_invoice_match_receipts(receipt_id) WHERE confirmed = 1;
CREATE INDEX idx_tax_match_receipts_receipt ON tax_invoice_match_receipts(receipt_id);

CREATE FUNCTION trg_tax_match_receipts_fixed_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF NEW.match_id <> OLD.match_id OR NEW.po_id <> OLD.po_id OR NEW.receipt_id <> OLD.receipt_id THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '세금계산서 대조의 연결 입고는 바꿀 수 없습니다';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER trg_tax_match_receipts_fixed BEFORE UPDATE ON tax_invoice_match_receipts FOR EACH ROW EXECUTE FUNCTION trg_tax_match_receipts_fixed_fn();

CREATE FUNCTION trg_tax_match_receipts_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF (SELECT status FROM tax_invoice_matches WHERE id = OLD.match_id) <> 'proposed' THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '확정·기각된 대조의 연결 입고는 지울 수 없습니다';
  END IF;
  RETURN OLD;
END
$fn$;
CREATE TRIGGER trg_tax_match_receipts_no_delete BEFORE DELETE ON tax_invoice_match_receipts FOR EACH ROW EXECUTE FUNCTION trg_tax_match_receipts_no_delete_fn();
