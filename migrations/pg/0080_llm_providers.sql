CREATE TABLE llm_providers (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                   TEXT NOT NULL UNIQUE CHECK (length(code) BETWEEN 2 AND 30 AND code !~ '[^a-z0-9-]'),
    kind                   TEXT NOT NULL CHECK (kind IN ('mock','anthropic','bedrock','vertex','openai_compat')),
    name                   TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 40),
    default_model          TEXT NOT NULL DEFAULT '' CHECK (length(default_model) <= 120),
    secret_sealed          TEXT NOT NULL DEFAULT '',
    hint                   TEXT NOT NULL DEFAULT '' CHECK (length(hint) <= 200),
    mode                   TEXT NOT NULL DEFAULT '' CHECK (length(mode) <= 30),
    external               BIGINT NOT NULL DEFAULT 1 CHECK (external IN (0,1)),
    supports_images        BIGINT NOT NULL DEFAULT 0 CHECK (supports_images IN (0,1)),
    price_in_micro_per_mtok  BIGINT NOT NULL DEFAULT 0 CHECK (price_in_micro_per_mtok >= 0),
    price_out_micro_per_mtok BIGINT NOT NULL DEFAULT 0 CHECK (price_out_micro_per_mtok >= 0),
    timeout_ms             BIGINT NOT NULL DEFAULT 30000 CHECK (timeout_ms BETWEEN 1000 AND 120000),
    active                 BIGINT NOT NULL DEFAULT 0 CHECK (active IN (0,1)),
    version                BIGINT NOT NULL DEFAULT 1 CHECK (version >= 1),
    created_by             BIGINT REFERENCES users(id),
    created_at             TEXT NOT NULL,
    updated_by             BIGINT REFERENCES users(id),
    updated_at             TEXT NOT NULL
);
