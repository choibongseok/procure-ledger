BEGIN
  IF TRUE THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '근무 유형 배정 이력은 지울 수 없습니다(추가 전용)';
  END IF;
  RETURN OLD;
END $fn$;
CREATE TRIGGER trg_work_assignments_no_delete BEFORE DELETE ON work_assignments FOR EACH ROW EXECUTE FUNCTION trg_work_assignments_no_delete_fn();

CREATE TABLE attendance_records (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id    BIGINT NOT NULL DEFAULT 1,
    user_id      BIGINT NOT NULL REFERENCES users(id),
    work_date    TEXT NOT NULL CHECK (work_date ~ '^[0-9][0-9][0-9][0-9]-[0-1][0-9]-[0-3][0-9]$'),
    check_in_at  TEXT NOT NULL DEFAULT '',
    check_out_at TEXT NOT NULL DEFAULT '',
    source       TEXT NOT NULL CHECK (source IN ('web','admin','correction')),
    created_at   TEXT NOT NULL,
    updated_at   TEXT NOT NULL,
    UNIQUE (user_id, work_date)
);
CREATE INDEX idx_attendance_records_date ON attendance_records(entity_id, work_date);
CREATE FUNCTION trg_attendance_records_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF TRUE THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '출퇴근 기록은 지울 수 없습니다(정정 줄로만 고칩니다)';
  END IF;
  RETURN OLD;
END $fn$;
CREATE TRIGGER trg_attendance_records_no_delete BEFORE DELETE ON attendance_records FOR EACH ROW EXECUTE FUNCTION trg_attendance_records_no_delete_fn();
CREATE FUNCTION trg_attendance_records_fixed_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF NEW.user_id IS DISTINCT FROM OLD.user_id OR NEW.work_date IS DISTINCT FROM OLD.work_date OR NEW.entity_id IS DISTINCT FROM OLD.entity_id THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '출퇴근 기록의 사용자·근무일은 고칠 수 없습니다';
  END IF;
  RETURN NEW;
END $fn$;
CREATE TRIGGER trg_attendance_records_fixed BEFORE UPDATE ON attendance_records FOR EACH ROW EXECUTE FUNCTION trg_attendance_records_fixed_fn();

CREATE TABLE attendance_corrections (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id    BIGINT NOT NULL DEFAULT 1,
    user_id      BIGINT NOT NULL REFERENCES users(id),
    work_date    TEXT NOT NULL CHECK (work_date ~ '^[0-9][0-9][0-9][0-9]-[0-1][0-9]-[0-3][0-9]$'),
    old_in       TEXT NOT NULL DEFAULT '',
    old_out      TEXT NOT NULL DEFAULT '',
    new_in       TEXT NOT NULL DEFAULT '',
    new_out      TEXT NOT NULL DEFAULT '',
    reason       TEXT NOT NULL CHECK (length(reason) BETWEEN 1 AND 200),
    requested_by BIGINT NOT NULL,
    status       TEXT NOT NULL CHECK (status IN ('requested','applied','rejected')),
    approved_by  BIGINT NOT NULL DEFAULT 0,
    decide_note  TEXT NOT NULL DEFAULT '' CHECK (length(decide_note) <= 200),
    created_at   TEXT NOT NULL,
    decided_at   TEXT NOT NULL DEFAULT ''
);
CREATE INDEX idx_attendance_corrections_user ON attendance_corrections(entity_id, user_id, work_date);
CREATE INDEX idx_attendance_corrections_status ON attendance_corrections(entity_id, status);
CREATE FUNCTION trg_attendance_corrections_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF TRUE THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '정정 줄은 지울 수 없습니다(추가 전용)';
  END IF;
  RETURN OLD;
END $fn$;
CREATE TRIGGER trg_attendance_corrections_no_delete BEFORE DELETE ON attendance_corrections FOR EACH ROW EXECUTE FUNCTION trg_attendance_corrections_no_delete_fn();
CREATE FUNCTION trg_attendance_corrections_fixed_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF NEW.user_id IS DISTINCT FROM OLD.user_id OR NEW.work_date IS DISTINCT FROM OLD.work_date OR NEW.old_in IS DISTINCT FROM OLD.old_in OR NEW.old_out IS DISTINCT FROM OLD.old_out OR NEW.new_in IS DISTINCT FROM OLD.new_in
  OR NEW.new_out IS DISTINCT FROM OLD.new_out OR NEW.reason IS DISTINCT FROM OLD.reason OR NEW.requested_by IS DISTINCT FROM OLD.requested_by OR NEW.entity_id IS DISTINCT FROM OLD.entity_id OR NEW.created_at IS DISTINCT FROM OLD.created_at
  OR OLD.status <> 'requested' THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '정정 줄은 고칠 수 없습니다(요청 중인 줄의 결정만 기록됩니다)';
  END IF;
  RETURN NEW;
END $fn$;
CREATE TRIGGER trg_attendance_corrections_fixed BEFORE UPDATE ON attendance_corrections FOR EACH ROW EXECUTE FUNCTION trg_attendance_corrections_fixed_fn();

CREATE TABLE attendance_closes (
    entity_id     BIGINT NOT NULL DEFAULT 1,
    month         TEXT NOT NULL CHECK (month ~ '^[0-9][0-9][0-9][0-9]-[0-1][0-9]$'),
    closed_by     BIGINT NOT NULL,
    closed_at     TEXT NOT NULL,
    reopened_by   BIGINT NOT NULL DEFAULT 0,
    reopened_at   TEXT NOT NULL DEFAULT '',
    reopen_reason TEXT NOT NULL DEFAULT '' CHECK (length(reopen_reason) <= 200),
    PRIMARY KEY (entity_id, month)
);
