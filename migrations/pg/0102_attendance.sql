  IF TRUE THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '근태 마감 기록은 지울 수 없습니다';
  END IF;
  RETURN OLD;
END $fn$;
CREATE TRIGGER trg_attendance_closes_no_delete BEFORE DELETE ON attendance_closes FOR EACH ROW EXECUTE FUNCTION trg_attendance_closes_no_delete_fn();

CREATE TABLE attendance_warnings (
    user_id    BIGINT NOT NULL REFERENCES users(id),
    week_start TEXT NOT NULL CHECK (week_start ~ '^[0-9][0-9][0-9][0-9]-[0-1][0-9]-[0-3][0-9]$'),
    level      TEXT NOT NULL CHECK (level IN ('caution','over')),
    created_at TEXT NOT NULL,
    PRIMARY KEY (user_id, week_start, level)
);
