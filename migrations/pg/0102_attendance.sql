-- 0102(PG): SQLite 0102_attendance.sql 의 짝이다.
-- 0102: 출퇴근·근무 유형·정정·근태 마감·주 근로시간 경고(B50 12.3,). 모두 법인 소유 표다(entity_id, 기본 법인 1). 날짜는 KST YYYY-MM-DD, 시각은 RFC3339 UTC.
--  - work_types: 근무 유형(고정 fixed·시차 staggered·선택 flexible). 지우지 않고 사용 중지만 한다. 배정이 없는 사람은 서비스의 기본 유형(고정 09:00~18:00, 휴게 12:00~13:00)으로 본다.
--  - work_assignments: 사람별 근무 유형 배정 이력(효력일, 추가 전용). 같은 사람·같은 효력일은 하나다.
--  - attendance_records: 하루 한 행(사용자·근무일 유일). 체크인·체크아웃은 서버 시각. 고치는 길은 정정 줄(attendance_corrections)을 거친 서비스뿐이고 행은 지울 수 없다.
--  - attendance_corrections: 정정 요청·결과 줄. 요청 때 이전 값과 새 값·사유가 정해지고 이후에는 상태(requested → applied·rejected)와 결정자만 바뀐다.
--  - attendance_closes: 법인×월 근태 마감. 해제하면 해제 정보가 남고 다시 마감하면 새로 쓴다(이력은 감사에 있다).
--  - attendance_warnings: 주 근로시간 경고 알림을 보낸 기록(사용자·주 시작일·단계 유일 = 같은 주 같은 단계는 한 번만 알린다).
CREATE TABLE work_types (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id     BIGINT NOT NULL DEFAULT 1,
    code          TEXT NOT NULL CHECK (code ~ '^[a-z]' AND length(code) BETWEEN 2 AND 30),
    name          TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 30),
    kind          TEXT NOT NULL CHECK (kind IN ('fixed','staggered','flexible')),
    start_time    TEXT NOT NULL DEFAULT '' CHECK (start_time = '' OR start_time ~ '^[0-2][0-9]:[0-5][0-9]$'),
    end_time      TEXT NOT NULL DEFAULT '' CHECK (end_time = '' OR end_time ~ '^[0-2][0-9]:[0-5][0-9]$'),
    break_start   TEXT NOT NULL DEFAULT '' CHECK (break_start = '' OR break_start ~ '^[0-2][0-9]:[0-5][0-9]$'),
    break_end     TEXT NOT NULL DEFAULT '' CHECK (break_end = '' OR break_end ~ '^[0-2][0-9]:[0-5][0-9]$'),
    core_start    TEXT NOT NULL DEFAULT '' CHECK (core_start = '' OR core_start ~ '^[0-2][0-9]:[0-5][0-9]$'),
    core_end      TEXT NOT NULL DEFAULT '' CHECK (core_end = '' OR core_end ~ '^[0-2][0-9]:[0-5][0-9]$'),
    weekly_minutes BIGINT NOT NULL DEFAULT 2400 CHECK (weekly_minutes BETWEEN 600 AND 3120),
    active        BIGINT NOT NULL DEFAULT 1 CHECK (active IN (0,1)),
    created_at    TEXT NOT NULL,
    UNIQUE (entity_id, code)
);
CREATE FUNCTION trg_work_types_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF TRUE THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '근무 유형은 지울 수 없습니다(사용 중지만 됩니다)';
  END IF;
  RETURN OLD;
END $fn$;
CREATE TRIGGER trg_work_types_no_delete BEFORE DELETE ON work_types FOR EACH ROW EXECUTE FUNCTION trg_work_types_no_delete_fn();

CREATE TABLE work_assignments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id    BIGINT NOT NULL DEFAULT 1,
    user_id      BIGINT NOT NULL REFERENCES users(id),
    work_type_id BIGINT NOT NULL REFERENCES work_types(id),
    valid_from   TEXT NOT NULL CHECK (valid_from ~ '^[0-9][0-9][0-9][0-9]-[0-1][0-9]-[0-3][0-9]$'),
    created_by   BIGINT NOT NULL DEFAULT 0,
    created_at   TEXT NOT NULL,
    UNIQUE (user_id, valid_from)
);
CREATE INDEX idx_work_assignments_user ON work_assignments(user_id, valid_from);
