CREATE FUNCTION trg_receipt_no_over_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  PERFORM 1 FROM po_lines WHERE id = NEW.po_line_id FOR UPDATE;
  IF (SELECT COALESCE(SUM(quantity), 0) FROM receipt_lines WHERE po_line_id = NEW.po_line_id) + NEW.quantity
        > (SELECT quantity FROM po_lines WHERE id = NEW.po_line_id) THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'PO 수량을 넘는 입고입니다';
  END IF;
  RETURN NEW;
END
