-- ProcureLedger PostgreSQL 기준 마이그레이션 (B37). SQLite 0001~0050 의 최종 스키마와 시드 데이터를 옮긴 것이다.
-- equivalent: sqlite 0050
-- 생성: go run ./internal/tools/pgbaseline (이후에는 이 파일이 정본이다. 새 마이그레이션은 migrations/NNNN_x.sql 과 migrations/pg/NNNN_x.sql 을 쌍으로 만든다)
-- 순서: 표 → 시드 데이터 → 식별자 시퀀스 → 색인 → 뷰 → 트리거(데이터 적재 중에는 보호 장치가 없다)

-- ============================ 표 ============================
CREATE TABLE departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oidc_sub      TEXT UNIQUE,
    email         TEXT NOT NULL UNIQUE,
    name          TEXT NOT NULL,
    role          TEXT NOT NULL DEFAULT '',
    position      TEXT CHECK (position IN ('team_lead','dept_head')),
    department_id BIGINT NOT NULL REFERENCES departments(id),
    active        BIGINT NOT NULL DEFAULT 1 CHECK (active IN (0,1)),
    created_at    TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS"Z"'))
);

CREATE TABLE sessions (
    id_hash      TEXT PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users(id),
    csrf_hash    TEXT NOT NULL,
    created_at   TEXT NOT NULL,
    expires_at   TEXT NOT NULL,
    last_seen_at TEXT NOT NULL,
    revoked_at   TEXT,
    auth_method TEXT NOT NULL DEFAULT 'oidc',
    setup TEXT
);

CREATE TABLE oidc_auth_requests (
    state         TEXT PRIMARY KEY,
    nonce         TEXT NOT NULL,
    code_verifier TEXT NOT NULL,
    redirect_to   TEXT NOT NULL DEFAULT '/',
    created_at    TEXT NOT NULL,
    expires_at    TEXT NOT NULL,
    provider TEXT NOT NULL DEFAULT 'oidc',
    purpose TEXT NOT NULL DEFAULT 'login',
    test_user_id BIGINT
);

CREATE TABLE personal_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users(id),
    name         TEXT NOT NULL,
    token_prefix TEXT NOT NULL,
    token_hash   TEXT NOT NULL UNIQUE,
    created_at   TEXT NOT NULL,
    expires_at   TEXT NOT NULL,
    revoked_at   TEXT,
    last_used_at TEXT
);

CREATE TABLE audit_logs (
    seq BIGINT PRIMARY KEY,
    at          TEXT NOT NULL,
    actor_id    BIGINT NOT NULL,
    actor_role  TEXT NOT NULL,
    channel     TEXT NOT NULL CHECK (channel IN ('web','mcp','llmgw')),
    action      TEXT NOT NULL,
    target_type TEXT NOT NULL,
    target_id   TEXT NOT NULL,
    result      TEXT NOT NULL CHECK (result IN ('success','denied','error')),
    diff        TEXT NOT NULL DEFAULT '[]',
    detail      TEXT NOT NULL DEFAULT '',
    prev_hash   TEXT NOT NULL,
    hash        TEXT NOT NULL UNIQUE
);

CREATE TABLE vendors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL,
    business_no TEXT NOT NULL DEFAULT '',
    account_no  TEXT NOT NULL DEFAULT '',
    phone       TEXT NOT NULL DEFAULT '',
    email       TEXT NOT NULL DEFAULT '',
    payment_days BIGINT CHECK (payment_days IS NULL OR payment_days BETWEEN 0 AND 365)
);

CREATE TABLE items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku          TEXT NOT NULL UNIQUE,
    name         TEXT NOT NULL,
    unit         TEXT NOT NULL DEFAULT 'EA',
    safety_stock BIGINT NOT NULL DEFAULT 0 CHECK (safety_stock >= 0),
    track_lot    BIGINT NOT NULL DEFAULT 0 CHECK (track_lot IN (0,1)),
    active       BIGINT NOT NULL DEFAULT 1 CHECK (active IN (0,1))
);

CREATE TABLE lots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id     BIGINT NOT NULL REFERENCES items(id),
    lot_no      TEXT NOT NULL,
    expiry_date TEXT,
    UNIQUE (item_id, lot_no)
);

CREATE TABLE approval_forms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                TEXT NOT NULL UNIQUE CHECK (code ~ '^[A-Z0-9].*$' AND length(code) <= 20),
    category            TEXT NOT NULL CHECK (category IN ('general','purchase','finance','cooperation','other')),
    name                TEXT NOT NULL CHECK (length(name) > 0),
