CREATE FUNCTION trg_approval_delegated_rules_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF NEW.on_behalf_of IS NOT NULL THEN
    IF NEW.action NOT IN ('approve','reject') THEN
      RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '위임 결재는 승인·반려에만 쓸 수 있습니다';
    END IF;
    IF NEW.on_behalf_of = NEW.actor_id THEN
      RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '본인을 대신해 결재할 수 없습니다';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM approval_delegations d
        WHERE d.delegator_id = NEW.on_behalf_of AND d.delegate_id = NEW.actor_id
          AND d.start_at <= NEW.at AND NEW.at < d.end_at
          AND (d.revoked_at IS NULL OR d.revoked_at > NEW.at)) THEN
      RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '유효한 위임이 없습니다';
    END IF;
  END IF;
  RETURN NEW;
END
