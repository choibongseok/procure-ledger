CREATE VIEW approval_step_current AS
SELECT a.pr_id, a.round, a.seq, a.user_id
  FROM approval_step_assignees a
 WHERE NOT EXISTS (SELECT 1 FROM approval_step_reassignments r WHERE r.pr_id = a.pr_id AND r.round = a.round AND r.seq = a.seq)
UNION ALL
SELECT r.pr_id, r.round, r.seq, r.to_user_id
  FROM approval_step_reassignments r
 WHERE r.id = (SELECT MAX(r2.id) FROM approval_step_reassignments r2 WHERE r2.pr_id = r.pr_id AND r2.round = r.round AND r2.seq = r.seq);

CREATE VIEW v_item_stock AS
SELECT i.id AS item_id, COALESCE(SUM(l.qty_delta)::BIGINT, 0) AS on_hand
FROM items i LEFT JOIN stock_ledger l ON l.item_id = i.id
GROUP BY i.id;

CREATE VIEW v_lot_stock AS
SELECT l.item_id, l.id AS lot_id, l.lot_no, l.expiry_date, COALESCE(SUM(s.qty_delta)::BIGINT, 0) AS on_hand
FROM lots l LEFT JOIN stock_ledger s ON s.lot_id = l.id
GROUP BY l.id;

CREATE VIEW v_wh_lot_stock AS
SELECT warehouse_id, item_id, COALESCE(lot_id, 0) AS lot_id, SUM(qty_delta)::BIGINT AS on_hand
FROM stock_ledger
GROUP BY warehouse_id, item_id, COALESCE(lot_id, 0);

