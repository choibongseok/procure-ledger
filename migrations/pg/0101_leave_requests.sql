CREATE TABLE leave_requests (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id             BIGINT NOT NULL DEFAULT 1,
    user_id               BIGINT NOT NULL REFERENCES users(id),
    doc_id                BIGINT NOT NULL UNIQUE REFERENCES purchase_requests(id),
    leave_code            TEXT NOT NULL,
    start_date            TEXT NOT NULL CHECK (start_date ~ '^[0-9]{4}-[0-1][0-9]-[0-3][0-9]$'),
    end_date              TEXT NOT NULL CHECK (end_date ~ '^[0-9]{4}-[0-1][0-9]-[0-3][0-9]$'),
    part                  TEXT NOT NULL CHECK (part IN ('full','am','pm','hours')),
    start_time            TEXT NOT NULL DEFAULT '',
    end_time              TEXT NOT NULL DEFAULT '',
    minutes               BIGINT NOT NULL CHECK (minutes > 0),
    balance               TEXT NOT NULL DEFAULT '' CHECK (balance IN ('','annual','compensatory')),
    status                TEXT NOT NULL CHECK (status IN ('pending','approved','rejected','recalled','canceled')),
    reason                TEXT NOT NULL DEFAULT '' CHECK (length(reason) <= 200),
    delegate_user_id      BIGINT NOT NULL DEFAULT 0,
    absence_delegation_id BIGINT NOT NULL DEFAULT 0,
    proof_attachment_id   BIGINT NOT NULL DEFAULT 0,
    note                  TEXT NOT NULL DEFAULT '' CHECK (length(note) <= 200),
    created_at            TEXT NOT NULL,
    updated_at            TEXT NOT NULL
);
CREATE INDEX idx_leave_requests_user ON leave_requests(entity_id, user_id, start_date);
CREATE INDEX idx_leave_requests_period ON leave_requests(entity_id, start_date, end_date);
CREATE FUNCTION trg_leave_requests_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '휴가 신청은 지울 수 없습니다';
END $fn$;
CREATE TRIGGER trg_leave_requests_no_delete BEFORE DELETE ON leave_requests FOR EACH ROW EXECUTE FUNCTION trg_leave_requests_no_delete_fn();
CREATE FUNCTION trg_leave_requests_transition_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF NEW.status <> OLD.status AND (OLD.status IN ('rejected','recalled','canceled') OR (OLD.status = 'approved' AND NEW.status <> 'canceled')) THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '휴가 신청 상태를 이 방향으로 바꿀 수 없습니다';
  END IF;
  RETURN NEW;
END $fn$;
CREATE TRIGGER trg_leave_requests_transition BEFORE UPDATE ON leave_requests FOR EACH ROW EXECUTE FUNCTION trg_leave_requests_transition_fn();
CREATE FUNCTION trg_leave_requests_fixed_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF NEW.user_id IS DISTINCT FROM OLD.user_id OR NEW.doc_id IS DISTINCT FROM OLD.doc_id OR NEW.leave_code IS DISTINCT FROM OLD.leave_code
     OR NEW.start_date IS DISTINCT FROM OLD.start_date OR NEW.end_date IS DISTINCT FROM OLD.end_date OR NEW.part IS DISTINCT FROM OLD.part
     OR NEW.minutes IS DISTINCT FROM OLD.minutes OR NEW.balance IS DISTINCT FROM OLD.balance OR NEW.entity_id IS DISTINCT FROM OLD.entity_id THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '휴가 신청의 신청 내용은 고칠 수 없습니다(취소 후 새로 신청하세요)';
  END IF;
  RETURN NEW;
END $fn$;
CREATE TRIGGER trg_leave_requests_fixed BEFORE UPDATE ON leave_requests FOR EACH ROW EXECUTE FUNCTION trg_leave_requests_fixed_fn();

