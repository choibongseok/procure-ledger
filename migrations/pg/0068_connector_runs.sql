CREATE TABLE connector_runs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mapping       TEXT NOT NULL CHECK (length(mapping) BETWEEN 1 AND 60),
    mapping_hash  TEXT NOT NULL,
    direction     TEXT NOT NULL CHECK (direction IN ('in','out')),
    target        TEXT NOT NULL,
    dry_run       BIGINT NOT NULL DEFAULT 0 CHECK (dry_run IN (0,1)),
    started_at    TEXT NOT NULL,
    finished_at   TEXT NOT NULL,
    rows_total    BIGINT NOT NULL DEFAULT 0 CHECK (rows_total >= 0),
    rows_ok       BIGINT NOT NULL DEFAULT 0 CHECK (rows_ok >= 0),
    rows_error    BIGINT NOT NULL DEFAULT 0 CHECK (rows_error >= 0),
    result_code   TEXT NOT NULL CHECK (result_code IN ('ok','dry_run','row_errors','failed')),
    audit_seq     BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_connector_runs_started ON connector_runs(started_at);
CREATE FUNCTION trg_connector_runs_no_update_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '커넥터 실행 이력은 고칠 수 없습니다';
  RETURN NEW;
END
$fn$;
CREATE TRIGGER trg_connector_runs_no_update BEFORE UPDATE ON connector_runs FOR EACH ROW EXECUTE FUNCTION trg_connector_runs_no_update_fn();
CREATE FUNCTION trg_connector_runs_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '커넥터 실행 이력은 지울 수 없습니다';
  RETURN OLD;
END
$fn$;
CREATE TRIGGER trg_connector_runs_no_delete BEFORE DELETE ON connector_runs FOR EACH ROW EXECUTE FUNCTION trg_connector_runs_no_delete_fn();

