CREATE TABLE entities (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code               TEXT NOT NULL UNIQUE CHECK (code ~ '^[A-Z0-9]{2,6}$'),
    name               TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 100),
    business_no        TEXT NOT NULL DEFAULT '' CHECK (length(business_no) <= 20),
    representative     TEXT NOT NULL DEFAULT '' CHECK (length(representative) <= 50),
    address            TEXT NOT NULL DEFAULT '' CHECK (length(address) <= 200),
    phone              TEXT NOT NULL DEFAULT '' CHECK (length(phone) <= 30),
    fiscal_start_month BIGINT NOT NULL DEFAULT 1 CHECK (fiscal_start_month BETWEEN 1 AND 12),
    root_unit_id       BIGINT REFERENCES org_units(id),
    is_default         BIGINT NOT NULL DEFAULT 0 CHECK (is_default IN (0,1)),
    active             BIGINT NOT NULL DEFAULT 1 CHECK (active IN (0,1)),
    version            BIGINT NOT NULL DEFAULT 1 CHECK (version >= 1),
    created_by         BIGINT REFERENCES users(id),
    created_at         TEXT NOT NULL,
    updated_by         BIGINT REFERENCES users(id),
    updated_at         TEXT NOT NULL
);
CREATE UNIQUE INDEX idx_entities_business_no ON entities(replace(business_no, '-', '')) WHERE business_no <> '';
CREATE UNIQUE INDEX idx_entities_root_unit ON entities(root_unit_id) WHERE root_unit_id IS NOT NULL;
CREATE UNIQUE INDEX idx_entities_default ON entities(is_default) WHERE is_default = 1;

CREATE FUNCTION trg_entities_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '법인은 지울 수 없습니다(사용 여부만 바꿉니다)';
  RETURN OLD;
END
$fn$;
CREATE TRIGGER trg_entities_no_delete BEFORE DELETE ON entities FOR EACH ROW EXECUTE FUNCTION trg_entities_no_delete_fn();

CREATE FUNCTION trg_entities_default_active_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF OLD.is_default = 1 AND (NEW.active = 0 OR NEW.is_default = 0) THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '기본 법인은 비활성화할 수 없습니다';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER trg_entities_default_active BEFORE UPDATE ON entities FOR EACH ROW EXECUTE FUNCTION trg_entities_default_active_fn();

