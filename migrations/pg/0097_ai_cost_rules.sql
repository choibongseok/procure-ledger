CREATE TABLE ai_cost_rule_sets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version          BIGINT NOT NULL UNIQUE CHECK (version >= 1),
    valid_from_month TEXT NOT NULL CHECK (valid_from_month ~ '^[0-9][0-9][0-9][0-9]-[0-1][0-9]$'),
    note             TEXT NOT NULL DEFAULT '' CHECK (length(note) <= 200),
    created_by       BIGINT NOT NULL REFERENCES users(id),
    created_at       TEXT NOT NULL
);

CREATE TABLE ai_cost_rule_pools (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_set_id   BIGINT NOT NULL REFERENCES ai_cost_rule_sets(id),
    seq           BIGINT NOT NULL CHECK (seq >= 1),
    name          TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 40),
    selector_json TEXT NOT NULL CHECK (length(selector_json) <= 2000),
    driver        TEXT NOT NULL CHECK (driver IN ('headcount','usage','fixed')),
    scope         TEXT NOT NULL DEFAULT 'entity' CHECK (scope IN ('entity','group')),
    targets_all   BIGINT NOT NULL DEFAULT 0 CHECK (targets_all IN (0,1)),
    UNIQUE (rule_set_id, seq)
);

CREATE TABLE ai_cost_rule_targets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pool_id       BIGINT NOT NULL REFERENCES ai_cost_rule_pools(id),
    department_id BIGINT NOT NULL,
    weight_pct    BIGINT NOT NULL DEFAULT 0 CHECK (weight_pct BETWEEN 0 AND 100),
    UNIQUE (pool_id, department_id)
);

