  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER trg_eval_items_published_no_update BEFORE UPDATE ON eval_items FOR EACH ROW EXECUTE FUNCTION trg_eval_items_published_no_update_fn();

CREATE FUNCTION trg_eval_items_published_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
