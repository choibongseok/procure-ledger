CREATE TABLE eval_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id   BIGINT NOT NULL REFERENCES eval_set_versions(id),
    seq          BIGINT NOT NULL CHECK (seq >= 1),
    question     TEXT NOT NULL CHECK (length(question) BETWEEN 1 AND 4000),
    context_json TEXT NOT NULL DEFAULT '' CHECK (length(context_json) <= 4000),
    expected     TEXT NOT NULL CHECK (length(expected) BETWEEN 1 AND 4000),
    grader       TEXT NOT NULL CHECK (grader IN ('exact','contains','number','llm')),
    tolerance    TEXT NOT NULL DEFAULT '' CHECK (length(tolerance) <= 20),
    rubric       TEXT NOT NULL DEFAULT '' CHECK (length(rubric) <= 2000),
    critical     BIGINT NOT NULL DEFAULT 0 CHECK (critical IN (0,1)),
    tags         TEXT NOT NULL DEFAULT '' CHECK (length(tags) <= 200),
    masked_count BIGINT NOT NULL DEFAULT 0 CHECK (masked_count >= 0),
    UNIQUE (version_id, seq)
);

CREATE FUNCTION trg_eval_items_published_no_insert_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF (SELECT status FROM eval_set_versions WHERE id = NEW.version_id) = 'published' THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '게시된 버전은 고칠 수 없습니다';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER trg_eval_items_published_no_insert BEFORE INSERT ON eval_items FOR EACH ROW EXECUTE FUNCTION trg_eval_items_published_no_insert_fn();

