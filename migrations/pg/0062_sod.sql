-- 0062 (B41 2단계): SoD 규칙 모드·위반·예외. SQLite 0062_sod.sql 의 짝이다(초안은 pgbaseline -translate, 검토함).
CREATE TABLE sod_rule_settings (
    rule_code  TEXT PRIMARY KEY CHECK (length(rule_code) BETWEEN 1 AND 40),
    mode       TEXT NOT NULL CHECK (mode IN ('off','warn','block')),
    updated_by BIGINT NOT NULL REFERENCES users(id),
    updated_at TEXT NOT NULL
);

CREATE TABLE sod_violations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at           TEXT NOT NULL,
    rule_code    TEXT NOT NULL,
    result       TEXT NOT NULL CHECK (result IN ('allowed','blocked','excepted')),
    mode         TEXT NOT NULL CHECK (mode IN ('warn','block')),
    kind         TEXT NOT NULL CHECK (kind IN ('txn','hold')),
    subject_type TEXT NOT NULL,
    subject_id   BIGINT NOT NULL,
    subject_no   TEXT NOT NULL DEFAULT '',
    actor_id     BIGINT NOT NULL,
    other_id     BIGINT NOT NULL DEFAULT 0,
    exception_id BIGINT,
    note         TEXT NOT NULL DEFAULT ''
);

CREATE INDEX idx_sod_violations_at ON sod_violations(at);

CREATE INDEX idx_sod_violations_rule ON sod_violations(rule_code, at);

CREATE FUNCTION trg_sod_violations_no_update_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'sod_violations 는 추가 전용입니다';
  RETURN NEW;
END
$fn$;
CREATE TRIGGER trg_sod_violations_no_update BEFORE UPDATE ON sod_violations FOR EACH ROW EXECUTE FUNCTION trg_sod_violations_no_update_fn();

CREATE FUNCTION trg_sod_violations_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'sod_violations 는 지울 수 없습니다';
  RETURN OLD;
END
$fn$;
CREATE TRIGGER trg_sod_violations_no_delete BEFORE DELETE ON sod_violations FOR EACH ROW EXECUTE FUNCTION trg_sod_violations_no_delete_fn();

CREATE TABLE sod_exceptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_code    TEXT NOT NULL,
    subject_type TEXT NOT NULL,
    subject_id   BIGINT NOT NULL,
    subject_no   TEXT NOT NULL DEFAULT '',
    user_id      BIGINT NOT NULL REFERENCES users(id),
    reason       TEXT NOT NULL CHECK (length(reason) BETWEEN 10 AND 300),
    requested_by BIGINT NOT NULL REFERENCES users(id),
    requested_at TEXT NOT NULL,
    approved_by  BIGINT REFERENCES users(id),
    approved_at  TEXT,
    status       TEXT NOT NULL CHECK (status IN ('requested','active','used','rejected','expired','revoked')),
    expires_at   TEXT,
    used_at      TEXT
);

CREATE INDEX idx_sod_exceptions_match ON sod_exceptions(rule_code, subject_type, subject_id, user_id, status);

