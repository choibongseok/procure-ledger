CREATE TABLE ai_cost_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    month            TEXT NOT NULL CHECK (month ~ '^[0-9][0-9][0-9][0-9]-[0-1][0-9]$'),
    entity_id        BIGINT NOT NULL,
    rule_version     BIGINT NOT NULL CHECK (rule_version >= 1),
    status           TEXT NOT NULL CHECK (status IN ('confirmed','released')),
    fx_usd_krw_x1000 BIGINT NOT NULL CHECK (fx_usd_krw_x1000 > 0),
    total_krw        BIGINT NOT NULL CHECK (total_krw >= 0),
    direct_krw       BIGINT NOT NULL CHECK (direct_krw >= 0),
    shared_krw       BIGINT NOT NULL CHECK (shared_krw >= 0),
    journal_no       TEXT NOT NULL DEFAULT '',
    confirmed_by     BIGINT NOT NULL REFERENCES users(id),
    confirmed_at     TEXT NOT NULL,
    released_by      BIGINT REFERENCES users(id),
    released_at      TEXT,
    detail_json      TEXT NOT NULL DEFAULT '' CHECK (length(detail_json) <= 200000)
);

CREATE UNIQUE INDEX idx_ai_cost_runs_confirmed ON ai_cost_runs(month, entity_id) WHERE status = 'confirmed';

CREATE INDEX idx_ai_cost_runs_month ON ai_cost_runs(month, entity_id, id);

CREATE FUNCTION trg_ai_cost_runs_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '배부 실행은 지울 수 없습니다';
  RETURN OLD;
END
$fn$;
CREATE TRIGGER trg_ai_cost_runs_no_delete BEFORE DELETE ON ai_cost_runs FOR EACH ROW EXECUTE FUNCTION trg_ai_cost_runs_no_delete_fn();

CREATE FUNCTION trg_ai_cost_runs_fixed_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF NEW.month <> OLD.month OR NEW.entity_id <> OLD.entity_id OR NEW.rule_version <> OLD.rule_version OR NEW.total_krw <> OLD.total_krw OR NEW.direct_krw <> OLD.direct_krw
  OR NEW.shared_krw <> OLD.shared_krw OR NEW.fx_usd_krw_x1000 <> OLD.fx_usd_krw_x1000 OR NEW.confirmed_by <> OLD.confirmed_by OR NEW.confirmed_at <> OLD.confirmed_at
  OR (OLD.status = 'released' AND NEW.status <> 'released') THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '확정한 배부 결과는 고칠 수 없습니다. 해제한 뒤 다시 확정하세요';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER trg_ai_cost_runs_fixed BEFORE UPDATE ON ai_cost_runs FOR EACH ROW EXECUTE FUNCTION trg_ai_cost_runs_fixed_fn();

