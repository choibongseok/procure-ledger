-- 0065 (B42 1단계): 변경 피드. SQLite 0065_change_events.sql 의 짝이다.
CREATE TABLE change_events (
    seq           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at            TEXT NOT NULL,
    resource      TEXT NOT NULL CHECK (resource IN ('item','vendor','purchase_order','receipt','journal','payable')),
    object_id     BIGINT NOT NULL,
    op            TEXT NOT NULL CHECK (op IN ('created','updated','status_changed','canceled')),
    status        TEXT NOT NULL DEFAULT '',
    actor_channel TEXT NOT NULL DEFAULT 'web' CHECK (actor_channel IN ('web','mcp','llmgw','cli','scim','api'))
);
CREATE INDEX idx_change_events_object ON change_events(resource, object_id, seq);

CREATE FUNCTION trg_change_events_no_update_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'change_events 는 추가 전용입니다';
  RETURN NEW;
END
$fn$;
CREATE TRIGGER trg_change_events_no_update BEFORE UPDATE ON change_events FOR EACH ROW EXECUTE FUNCTION trg_change_events_no_update_fn();

CREATE FUNCTION trg_change_events_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'change_events 는 추가 전용입니다';
  RETURN OLD;
END
$fn$;
CREATE TRIGGER trg_change_events_no_delete BEFORE DELETE ON change_events FOR EACH ROW EXECUTE FUNCTION trg_change_events_no_delete_fn();
