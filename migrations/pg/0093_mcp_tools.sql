CREATE TABLE mcp_tools (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            TEXT NOT NULL UNIQUE CHECK (length(name) BETWEEN 10 AND 39 AND substr(name, 1, 7) = 'custom_' AND substr(name, 8) !~ '[^a-z0-9_]'),
    title           TEXT NOT NULL CHECK (length(title) BETWEEN 1 AND 60),
    kind            TEXT NOT NULL CHECK (kind IN ('read','draft')),
    current_version BIGINT NOT NULL DEFAULT 0,
    enabled         BIGINT NOT NULL DEFAULT 0 CHECK (enabled IN (0,1)),
    rate_per_min    BIGINT NOT NULL DEFAULT 30 CHECK (rate_per_min BETWEEN 1 AND 60),
    eval_set_id     BIGINT NOT NULL DEFAULT 0,
    created_by      BIGINT REFERENCES users(id),
    created_at      TEXT NOT NULL,
    updated_at      TEXT NOT NULL
);

CREATE TABLE mcp_tool_versions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tool_id          BIGINT NOT NULL REFERENCES mcp_tools(id),
    version          BIGINT NOT NULL CHECK (version >= 1),
    definition_json  TEXT NOT NULL,
    def_hash         TEXT NOT NULL,
    description      TEXT NOT NULL DEFAULT '' CHECK (length(description) <= 2400),
    note             TEXT NOT NULL DEFAULT '' CHECK (length(note) <= 200),
    resource_version BIGINT NOT NULL DEFAULT 1,
    created_by       BIGINT REFERENCES users(id),
    created_at       TEXT NOT NULL,
    UNIQUE (tool_id, version)
);

CREATE FUNCTION trg_mcp_tool_versions_no_update_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '도구 버전은 고칠 수 없습니다';
  RETURN NEW;
END
$fn$;
CREATE TRIGGER trg_mcp_tool_versions_no_update BEFORE UPDATE ON mcp_tool_versions FOR EACH ROW EXECUTE FUNCTION trg_mcp_tool_versions_no_update_fn();

CREATE FUNCTION trg_mcp_tool_versions_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '도구 버전은 고칠 수 없습니다';
  RETURN OLD;
END
$fn$;
CREATE TRIGGER trg_mcp_tool_versions_no_delete BEFORE DELETE ON mcp_tool_versions FOR EACH ROW EXECUTE FUNCTION trg_mcp_tool_versions_no_delete_fn();
