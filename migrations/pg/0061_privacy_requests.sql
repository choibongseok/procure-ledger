ALTER TABLE privacy_access_log DROP CONSTRAINT privacy_access_log_channel_check;
ALTER TABLE privacy_access_log ADD CONSTRAINT privacy_access_log_channel_check CHECK (channel IN ('web','mcp','llmgw','cli','scim','api'));

CREATE TABLE privacy_subject_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL REFERENCES users(id),
    status        TEXT NOT NULL CHECK (status IN ('requested','approved','rejected','expired')),
    period_from   TEXT NOT NULL,
    period_to     TEXT NOT NULL,
    reason        TEXT NOT NULL DEFAULT '' CHECK (length(reason) <= 200),
    requested_at  TEXT NOT NULL,
    decided_by    BIGINT REFERENCES users(id),
    decided_at    TEXT,
    decision_note TEXT NOT NULL DEFAULT '' CHECK (length(decision_note) <= 200),
    expires_at    TEXT
);

CREATE UNIQUE INDEX idx_privacy_req_open ON privacy_subject_requests(user_id) WHERE status = 'requested';

CREATE INDEX idx_privacy_req_user ON privacy_subject_requests(user_id, requested_at);

CREATE TABLE privacy_request_results (
    request_id  BIGINT NOT NULL REFERENCES privacy_subject_requests(id),
    seq         BIGINT NOT NULL,
    at          TEXT NOT NULL,
    viewer_unit TEXT NOT NULL,
    viewer_role TEXT NOT NULL,
    category    TEXT NOT NULL,
    screen      TEXT NOT NULL,
    fields      TEXT NOT NULL,
    is_export   BIGINT NOT NULL,
    summary     BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (request_id, seq)
);

