CREATE TABLE privacy_access_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at            TEXT NOT NULL,
    actor_id      BIGINT NOT NULL,
    actor_role    TEXT NOT NULL,
    channel       TEXT NOT NULL CHECK (channel IN ('web','mcp','llmgw','cli','scim')),
    token_id      BIGINT,
    category      TEXT NOT NULL CHECK (category IN ('contact','account','card','employee_no')),
    screen        TEXT NOT NULL CHECK (length(screen) BETWEEN 1 AND 80),
    dataset       TEXT NOT NULL DEFAULT '',
    is_export     BIGINT NOT NULL DEFAULT 0 CHECK (is_export IN (0,1)),
    fields        TEXT NOT NULL DEFAULT '[]',
    subject_count BIGINT NOT NULL CHECK (subject_count >= 0),
    subjects_hash TEXT NOT NULL,
    exposure      TEXT NOT NULL DEFAULT 'raw' CHECK (exposure IN ('raw','mcp_anomaly')),
    prev_hash     TEXT NOT NULL,
    hash          TEXT NOT NULL UNIQUE
);

CREATE INDEX idx_privacy_log_at ON privacy_access_log(at);

CREATE INDEX idx_privacy_log_actor ON privacy_access_log(actor_id, at);

CREATE TABLE privacy_access_subjects (
    log_id       BIGINT NOT NULL REFERENCES privacy_access_log(id),
    subject_type TEXT NOT NULL CHECK (subject_type IN ('user','vendor','company','payment')),
    subject_id   BIGINT NOT NULL,
    PRIMARY KEY (log_id, subject_type, subject_id)
);

CREATE INDEX idx_privacy_subjects_subject ON privacy_access_subjects(subject_type, subject_id, log_id);

CREATE TABLE privacy_log_segments (
    month     TEXT PRIMARY KEY CHECK (month ~ '^[0-9][0-9][0-9][0-9]-[0-1][0-9]$'),
    first_id  BIGINT NOT NULL,
    last_id   BIGINT NOT NULL,
    rows      BIGINT NOT NULL,
    head_hash TEXT NOT NULL,
    prev_hash TEXT NOT NULL,
    purged_at TEXT NOT NULL
);

CREATE TABLE privacy_write_guard (
    id BIGINT PRIMARY KEY CHECK (id = 1)
);

CREATE FUNCTION trg_privacy_log_no_update_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'privacy_access_log 는 추가 전용입니다';
  RETURN NEW;
END
$fn$;
CREATE TRIGGER trg_privacy_log_no_update BEFORE UPDATE ON privacy_access_log FOR EACH ROW EXECUTE FUNCTION trg_privacy_log_no_update_fn();

CREATE FUNCTION trg_privacy_log_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM privacy_write_guard) THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'privacy_access_log 는 보관 기간 파기 외에는 지울 수 없습니다';
  END IF;
  RETURN OLD;
END
$fn$;
CREATE TRIGGER trg_privacy_log_no_delete BEFORE DELETE ON privacy_access_log FOR EACH ROW EXECUTE FUNCTION trg_privacy_log_no_delete_fn();

