-- 0090 (B47 2단계): SQLite 0090_knowledge_uploads.sql 의 짝이다. 관리자가 올린 매뉴얼·규정. 열람 범위는 규정 머리말과 같은 의미(역할 AND 부서, 법인)이고 값은 머리말 원문 형식이다
-- ("all" 또는 쉼표 목록: roles 는 역할 이름·권한 이름, departments 는 부서 이름). 행은 지우지 않는다: 삭제는 removed_at 표시 + 내용 비움이고 조각은 같은 트랜잭션에서 지운다.
-- 새 버전은 이전 행을 removed_reason = 'replaced' 로 닫고(내용은 이력으로 남긴다) replaces_id 로 잇는다. entity_id 0 = 전 법인 공통(그룹 범위 관리자만).
CREATE TABLE knowledge_uploads (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id      BIGINT NOT NULL DEFAULT 1,
    kind           TEXT NOT NULL CHECK (kind IN ('manual','regulation')),
    title          TEXT NOT NULL CHECK (length(title) BETWEEN 1 AND 100),
    slug           TEXT NOT NULL,
    version        BIGINT NOT NULL DEFAULT 1 CHECK (version >= 1),
    replaces_id    BIGINT NOT NULL DEFAULT 0,
    roles          TEXT NOT NULL CHECK (length(roles) BETWEEN 1 AND 400),
    departments    TEXT NOT NULL CHECK (length(departments) BETWEEN 1 AND 800),
    filename       TEXT NOT NULL DEFAULT '',
    content_type   TEXT NOT NULL DEFAULT '',
    size           BIGINT NOT NULL DEFAULT 0 CHECK (size >= 0),
    sha256         TEXT NOT NULL DEFAULT '',
    content        BYTEA NOT NULL,
    uploaded_by    BIGINT NOT NULL DEFAULT 0,
    uploaded_at    TEXT NOT NULL,
    removed_at     TEXT,
    removed_by     BIGINT NOT NULL DEFAULT 0,
    removed_reason TEXT NOT NULL DEFAULT '' CHECK (removed_reason IN ('','removed','replaced'))
);
CREATE UNIQUE INDEX idx_knowledge_uploads_slug ON knowledge_uploads(entity_id, slug) WHERE removed_at IS NULL;
CREATE INDEX idx_knowledge_uploads_sha ON knowledge_uploads(entity_id, sha256);

CREATE FUNCTION trg_knowledge_uploads_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '업로드 문서는 지울 수 없습니다(삭제는 표시와 내용 비움으로 합니다)';
  RETURN OLD;
END
$fn$;
CREATE TRIGGER trg_knowledge_uploads_no_delete BEFORE DELETE ON knowledge_uploads FOR EACH ROW EXECUTE FUNCTION trg_knowledge_uploads_no_delete_fn();
