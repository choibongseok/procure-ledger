CREATE TABLE leave_types (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id      BIGINT NOT NULL DEFAULT 1,
    code           TEXT NOT NULL CHECK (code ~ '^[a-z]' AND length(code) BETWEEN 2 AND 30),
    name           TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 30),
    unit           TEXT NOT NULL CHECK (unit IN ('day','hour')),
    balance        TEXT NOT NULL DEFAULT '' CHECK (balance IN ('','annual','compensatory')),
    paid           BIGINT NOT NULL DEFAULT 1 CHECK (paid IN (0,1)),
    proof_required BIGINT NOT NULL DEFAULT 0 CHECK (proof_required IN (0,1)),
    max_days       BIGINT NOT NULL DEFAULT 0 CHECK (max_days >= 0),
    system         BIGINT NOT NULL DEFAULT 0 CHECK (system IN (0,1)),
    active         BIGINT NOT NULL DEFAULT 1 CHECK (active IN (0,1)),
    created_at     TEXT NOT NULL,
    UNIQUE (entity_id, code)
);
CREATE FUNCTION trg_leave_types_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '휴가 종류는 지울 수 없습니다(사용 중지만 됩니다)';
END $fn$;
CREATE TRIGGER trg_leave_types_no_delete BEFORE DELETE ON leave_types FOR EACH ROW EXECUTE FUNCTION trg_leave_types_no_delete_fn();

CREATE TABLE leave_policies (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id          BIGINT NOT NULL DEFAULT 1,
    effective_from     TEXT NOT NULL CHECK (effective_from ~ '^[0-9]{4}-[0-1][0-9]-[0-3][0-9]$'),
    basis              TEXT NOT NULL CHECK (basis IN ('hire','fiscal')),
    workday_minutes    BIGINT NOT NULL CHECK (workday_minutes BETWEEN 360 AND 600),
    hour_unit_minutes  BIGINT NOT NULL CHECK (hour_unit_minutes IN (30,60)),
    attendance_rule    BIGINT NOT NULL DEFAULT 1 CHECK (attendance_rule IN (0,1)),
    carry_max_minutes  BIGINT NOT NULL DEFAULT 0 CHECK (carry_max_minutes >= -1),
    carry_valid_months BIGINT NOT NULL DEFAULT 12 CHECK (carry_valid_months BETWEEN 1 AND 24),
    expire_months      BIGINT NOT NULL DEFAULT 12 CHECK (expire_months BETWEEN 12 AND 60),
    first_year_mode    TEXT NOT NULL DEFAULT 'monthly' CHECK (first_year_mode IN ('monthly','upfront')),
    created_by         BIGINT NOT NULL DEFAULT 0,
    created_at         TEXT NOT NULL,
    canceled           BIGINT NOT NULL DEFAULT 0 CHECK (canceled IN (0,1)),
    canceled_by        BIGINT NOT NULL DEFAULT 0,
    canceled_at        TEXT
);
CREATE UNIQUE INDEX idx_leave_policies_effective ON leave_policies(entity_id, effective_from) WHERE canceled = 0;
CREATE FUNCTION trg_leave_policies_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '휴가 규칙 이력은 지울 수 없습니다';
END $fn$;
CREATE TRIGGER trg_leave_policies_no_delete BEFORE DELETE ON leave_policies FOR EACH ROW EXECUTE FUNCTION trg_leave_policies_no_delete_fn();
CREATE FUNCTION trg_leave_policies_fixed_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF NEW.entity_id IS DISTINCT FROM OLD.entity_id OR NEW.effective_from IS DISTINCT FROM OLD.effective_from OR NEW.basis IS DISTINCT FROM OLD.basis
     OR NEW.workday_minutes IS DISTINCT FROM OLD.workday_minutes OR NEW.hour_unit_minutes IS DISTINCT FROM OLD.hour_unit_minutes
     OR NEW.attendance_rule IS DISTINCT FROM OLD.attendance_rule OR NEW.carry_max_minutes IS DISTINCT FROM OLD.carry_max_minutes
     OR NEW.carry_valid_months IS DISTINCT FROM OLD.carry_valid_months OR NEW.expire_months IS DISTINCT FROM OLD.expire_months
     OR NEW.first_year_mode IS DISTINCT FROM OLD.first_year_mode OR NEW.created_by IS DISTINCT FROM OLD.created_by
     OR NEW.created_at IS DISTINCT FROM OLD.created_at OR NEW.canceled < OLD.canceled THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '휴가 규칙 이력은 고칠 수 없습니다(취소만 됩니다)';
  END IF;
  RETURN NEW;
END $fn$;
CREATE TRIGGER trg_leave_policies_fixed BEFORE UPDATE ON leave_policies FOR EACH ROW EXECUTE FUNCTION trg_leave_policies_fixed_fn();

CREATE TABLE leave_ledger (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id  BIGINT NOT NULL DEFAULT 1,
    user_id    BIGINT NOT NULL REFERENCES users(id),
    balance    TEXT NOT NULL CHECK (balance IN ('annual','compensatory')),
    kind       TEXT NOT NULL CHECK (kind IN ('grant','carry','expire','reserve','release','use','adjust','opening')),
    minutes    BIGINT NOT NULL CHECK (minutes <> 0),
    period_key TEXT NOT NULL DEFAULT '',
    expires_on TEXT NOT NULL DEFAULT '',
    ref_type   TEXT NOT NULL DEFAULT '',
    ref_id     BIGINT NOT NULL DEFAULT 0,
    reason     TEXT NOT NULL DEFAULT '' CHECK (length(reason) <= 200),
    created_by BIGINT NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL
);
CREATE INDEX idx_leave_ledger_user ON leave_ledger(user_id, balance, id);
CREATE INDEX idx_leave_ledger_ref ON leave_ledger(ref_type, ref_id);
CREATE UNIQUE INDEX idx_leave_ledger_period ON leave_ledger(user_id, balance, kind, period_key) WHERE kind IN ('grant','carry','expire') AND period_key <> '';
CREATE FUNCTION trg_leave_ledger_no_update_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '휴가 원장은 고칠 수 없습니다(추가 전용)';
END $fn$;
CREATE TRIGGER trg_leave_ledger_no_update BEFORE UPDATE ON leave_ledger FOR EACH ROW EXECUTE FUNCTION trg_leave_ledger_no_update_fn();
CREATE FUNCTION trg_leave_ledger_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '휴가 원장은 지울 수 없습니다(추가 전용)';
END $fn$;
CREATE TRIGGER trg_leave_ledger_no_delete BEFORE DELETE ON leave_ledger FOR EACH ROW EXECUTE FUNCTION trg_leave_ledger_no_delete_fn();
