CREATE TABLE notification_targets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 TEXT NOT NULL UNIQUE CHECK (length(name) BETWEEN 1 AND 40),
    type                 TEXT NOT NULL CHECK (type IN ('slack','teams','kakaowork')),
    secret_sealed        TEXT NOT NULL,
    hint                 TEXT NOT NULL DEFAULT '',
    kinds_json           TEXT NOT NULL DEFAULT '[]',
    active               BIGINT NOT NULL DEFAULT 1 CHECK (active IN (0,1)),
    paused_reason        TEXT NOT NULL DEFAULT '' CHECK (paused_reason IN ('','auto')),
    consecutive_failures BIGINT NOT NULL DEFAULT 0 CHECK (consecutive_failures >= 0),
    last_ok_at           TEXT NOT NULL DEFAULT '',
    last_error_code      TEXT NOT NULL DEFAULT '',
    last_error_at        TEXT NOT NULL DEFAULT '',
    created_by           BIGINT REFERENCES users(id),
    created_at           TEXT NOT NULL,
    updated_at           TEXT NOT NULL
);

CREATE FUNCTION trg_notification_targets_type_fixed_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF NEW.type <> OLD.type OR NEW.created_at <> OLD.created_at OR NEW.created_by IS DISTINCT FROM OLD.created_by THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '웹훅 대상의 종류는 바꿀 수 없습니다';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER trg_notification_targets_type_fixed BEFORE UPDATE OF type, created_at, created_by ON notification_targets FOR EACH ROW EXECUTE FUNCTION trg_notification_targets_type_fixed_fn();

CREATE FUNCTION trg_notification_targets_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '웹훅 대상은 지울 수 없습니다(사용 중지만 됩니다)';
  RETURN OLD;
END
$fn$;
CREATE TRIGGER trg_notification_targets_no_delete BEFORE DELETE ON notification_targets FOR EACH ROW EXECUTE FUNCTION trg_notification_targets_no_delete_fn();

