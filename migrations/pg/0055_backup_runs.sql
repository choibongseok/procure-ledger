CREATE TABLE backup_runs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind        TEXT NOT NULL CHECK (kind IN ('backup','restore','rehearsal')),
    started_at  TEXT NOT NULL,
    finished_at TEXT NOT NULL,
    result      TEXT NOT NULL CHECK (result IN ('success','failed')),
    set_name    TEXT NOT NULL DEFAULT '',
    db_kind     TEXT NOT NULL DEFAULT '',
    bytes       BIGINT NOT NULL DEFAULT 0,
    chain_seq   BIGINT NOT NULL DEFAULT 0,
    error_code  TEXT NOT NULL DEFAULT '',
    tool_version TEXT NOT NULL DEFAULT '',
    warnings    TEXT NOT NULL DEFAULT ''
);
CREATE INDEX idx_backup_runs_kind ON backup_runs(kind, id);

CREATE FUNCTION trg_backup_runs_no_update_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'backup_runs 는 추가 전용입니다';
  RETURN NEW;
END
$fn$;
CREATE TRIGGER trg_backup_runs_no_update BEFORE UPDATE ON backup_runs FOR EACH ROW EXECUTE FUNCTION trg_backup_runs_no_update_fn();

CREATE FUNCTION trg_backup_runs_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'backup_runs 는 추가 전용입니다';
  RETURN OLD;
END
$fn$;
CREATE TRIGGER trg_backup_runs_no_delete BEFORE DELETE ON backup_runs FOR EACH ROW EXECUTE FUNCTION trg_backup_runs_no_delete_fn();
