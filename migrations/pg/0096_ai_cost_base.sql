ALTER TABLE llm_usage ADD COLUMN entity_id BIGINT NOT NULL DEFAULT 0;

UPDATE llm_usage SET entity_id = COALESCE((SELECT s.entity_id FROM org_unit_spans s WHERE s.unit_id = llm_usage.department_id ORDER BY s.valid_from DESC LIMIT 1), 1);

CREATE INDEX idx_llm_usage_entity_at ON llm_usage(entity_id, at);

CREATE TABLE ai_cost_fx (
    month           TEXT PRIMARY KEY CHECK (month ~ '^[0-9][0-9][0-9][0-9]-[0-1][0-9]$'),
    usd_krw_x1000   BIGINT NOT NULL CHECK (usd_krw_x1000 BETWEEN 1000 AND 100000000),
    set_by          BIGINT NOT NULL REFERENCES users(id),
    set_at          TEXT NOT NULL
);

CREATE TABLE ai_cost_adjustments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    month         TEXT NOT NULL CHECK (month ~ '^[0-9][0-9][0-9][0-9]-[0-1][0-9]$'),
    provider_code TEXT NOT NULL CHECK (length(provider_code) BETWEEN 1 AND 40),
    actual_krw    BIGINT NOT NULL CHECK (actual_krw >= 0),
    note          TEXT NOT NULL DEFAULT '' CHECK (length(note) <= 200),
    entered_by    BIGINT NOT NULL REFERENCES users(id),
    entered_at    TEXT NOT NULL
);

CREATE INDEX idx_ai_cost_adjustments_month ON ai_cost_adjustments(month, provider_code, id);

CREATE FUNCTION trg_ai_cost_adjustments_no_update_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '청구액 입력은 고칠 수 없습니다(새로 입력하세요)';
  RETURN NEW;
END
$fn$;
CREATE TRIGGER trg_ai_cost_adjustments_no_update BEFORE UPDATE ON ai_cost_adjustments FOR EACH ROW EXECUTE FUNCTION trg_ai_cost_adjustments_no_update_fn();

CREATE FUNCTION trg_ai_cost_adjustments_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '청구액 입력은 지울 수 없습니다';
  RETURN OLD;
END
$fn$;
CREATE TRIGGER trg_ai_cost_adjustments_no_delete BEFORE DELETE ON ai_cost_adjustments FOR EACH ROW EXECUTE FUNCTION trg_ai_cost_adjustments_no_delete_fn();

