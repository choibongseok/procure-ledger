CREATE TABLE eval_sets (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            TEXT NOT NULL UNIQUE CHECK (length(code) BETWEEN 2 AND 30 AND code !~ '[^a-z0-9-]'),
    name            TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 60),
    purpose         TEXT NOT NULL CHECK (purpose IN ('doc','policy','tool','text')),
    description     TEXT NOT NULL DEFAULT '' CHECK (length(description) <= 500),
    current_version BIGINT NOT NULL DEFAULT 0,
    baseline_run_id BIGINT NOT NULL DEFAULT 0,
    gate_drop_pct   BIGINT NOT NULL DEFAULT 2 CHECK (gate_drop_pct BETWEEN 0 AND 100),
    active          BIGINT NOT NULL DEFAULT 1 CHECK (active IN (0,1)),
    created_by      BIGINT REFERENCES users(id),
    created_at      TEXT NOT NULL,
    updated_at      TEXT NOT NULL
);

CREATE TABLE eval_set_versions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    set_id       BIGINT NOT NULL REFERENCES eval_sets(id),
    version      BIGINT NOT NULL CHECK (version >= 1),
    status       TEXT NOT NULL CHECK (status IN ('draft','published')),
    revision     BIGINT NOT NULL DEFAULT 1 CHECK (revision >= 1),
    items_hash   TEXT NOT NULL DEFAULT '',
    note         TEXT NOT NULL DEFAULT '' CHECK (length(note) <= 200),
    published_by BIGINT REFERENCES users(id),
    published_at TEXT NOT NULL DEFAULT '',
    created_by   BIGINT REFERENCES users(id),
    created_at   TEXT NOT NULL,
    UNIQUE (set_id, version)
);
CREATE UNIQUE INDEX idx_eval_set_versions_one_draft ON eval_set_versions(set_id) WHERE status = 'draft';

CREATE FUNCTION trg_eval_set_versions_published_no_update_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF OLD.status = 'published' THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '게시된 버전은 고칠 수 없습니다';
  END IF;
  RETURN NEW;
END
$fn$;
CREATE TRIGGER trg_eval_set_versions_published_no_update BEFORE UPDATE ON eval_set_versions FOR EACH ROW EXECUTE FUNCTION trg_eval_set_versions_published_no_update_fn();

CREATE FUNCTION trg_eval_set_versions_published_no_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF OLD.status = 'published' THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = '게시된 버전은 고칠 수 없습니다';
  END IF;
  RETURN OLD;
END
$fn$;
CREATE TRIGGER trg_eval_set_versions_published_no_delete BEFORE DELETE ON eval_set_versions FOR EACH ROW EXECUTE FUNCTION trg_eval_set_versions_published_no_delete_fn();
